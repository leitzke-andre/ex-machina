#!/usr/bin/env python3
"""Writes Ex-Machina/exm_tables.py, the tables the FL Studio script needs from the rest of the repository: which CC each button sends in the
'FL Studio' preset (with and without Shift), the LED index of each pad, and the device's 5 x 7 font (for drawing text as pixels on a firmware
without the TEXT command). FL Studio runs the script folder on its own, so the script cannot import the repository: these are copies, and
--check fails when they are stale (run_tests.sh runs it).

    gen_tables.py [--check]"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools', 'midi_patch'))
import mmk3_config as mc
import build_patch as bp

OUT = os.path.join(HERE, 'Ex-Machina', 'exm_tables.py')

def text():
    cfg = next(p['cfg'] for p in mc.builtin_presets() if p['id'] == 'fl-studio')
    f = mc.FIELDS
    act = lambda k, shifted: cfg[f['btn_act2' if shifted else 'btn_act'][0] + k]
    par = lambda k, shifted: cfg[f['btn_cc2' if shifted else 'btn_cc'][0] + k]
    plain = {mc.BUTTON_NAMES[k]: par(k, False) for k in range(41) if act(k, False) == mc.ACT_CC and par(k, False) != 0xFF}
    shifted = {mc.BUTTON_NAMES[k]: par(k, True) for k in range(41) if act(k, True) == mc.ACT_CC and par(k, True) != 0xFF}
    local = sorted(mc.BUTTON_NAMES[k] for k in range(41) if act(k, False) not in (mc.ACT_CC, mc.ACT_NONE))
    pad_note = {n: cfg[f['pad_note'][0] + mc.PAD_LABEL.index(n)] for n in range(1, 17)}
    pad_led = {n: cfg[f['pad_led'][0] + mc.PAD_LABEL.index(n)] for n in range(1, 17)}
    btn_led = {mc.BUTTON_NAMES[k]: k for k in range(39)}
    L = ['"""Generated by integrations/fl_studio/gen_tables.py from the \'FL Studio\' preset (tools/midi_patch/mmk3_config.py) and the device font', '(tools/midi_patch/build_patch.py). Do not edit: run gen_tables.py again."""', '']
    L.append(f'CHANNEL = {cfg[f["channel"][0]]}                                   # MIDI channel of the controls (0 = 1)')
    L.append(f'LED_CHANNEL = {cfg[f["led_channel"][0]]}                               # LED n = Note On n on this channel, velocity = colour code')
    L.append(f'ENC_CC, STRIP_CC = {cfg[f["enc_cc"][0]]}, {cfg[f["strip_cc"][0]]}                        # the encoder (relative, two\'s complement) and the strip')
    L.append(f'BUTTON_CC = {plain!r}')
    L.append(f'SHIFT_CC = {shifted!r}')
    L.append(f'LOCAL = {local!r}                     # buttons the device handles itself (they send no CC)')
    L.append(f'PAD_NOTE = {pad_note!r}')
    L.append(f'PAD_LED = {pad_led!r}')
    L.append(f'BUTTON_LED = {btn_led!r}')
    L.append(f'COLOURS = {mc.COLOUR_NAMES!r}                     # colour code = colour * 4 + brightness; colour 1 = the first name')
    L.append(f'FONT = bytes.fromhex({bp.FONT.hex()!r})   # ASCII 32..95, 5 column bytes each, bit 0 = top row')
    L.append(f'CMD_HOST, CMD_TEXT = {mc.CMD_HOST:#04x}, {mc.CMD_TEXT:#04x}')
    L.append(f'HOST_SCREEN, HOST_RAW, HOST_QUIET = {mc.HOST_SCREEN}, {mc.HOST_RAW}, {mc.HOST_QUIET}')
    return '\n'.join(L) + '\n'

if __name__ == '__main__':
    t = text()
    if '--check' in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != t: print('FAIL: Ex-Machina/exm_tables.py is stale: run integrations/fl_studio/gen_tables.py'); sys.exit(1)
        print('exm_tables.py is up to date')
    else:
        open(OUT, 'w').write(t); print('written', OUT)
