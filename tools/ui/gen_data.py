#!/usr/bin/env python3
"""Writes mmk3_data.js, the tables of the browser UI, from tools/midi_patch/mmk3_config.py (the one place that defines the config block,
its ranges, the NI button map and the defaults), so the JavaScript cannot drift away from the firmware's host library.

    gen_data.py [--check]     write tools/ui/mmk3_data.js (--check: only fail if the file on disk differs)"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'midi_patch'))
import mmk3_config as mc

def render():
    presets = {
        'default': mc.default_cfg(),                                  # MIDI Start / Stop for Play / Stop, pads from note 36, local LEDs
        'transport_cc': mc.default_cfg(transport='cc'),               # NI's CC 57 / 58 / 59
        'transport_mmc': mc.default_cfg(transport='mmc'),             # MIDI Machine Control
        'pads_ni': mc.default_cfg(pad_base=12),                       # NI's own pad notes 12..27
        'leds_off': mc.default_cfg(local_leds=False),
    }
    data = {
        'FW_NAME': mc.FW_NAME, 'FW_VERSION': mc.FW_VERSION, 'CFG_SIZE': mc.CFG_SIZE, 'PROTO_VERSION': mc.PROTO_VERSION,
        'ACTION_NAMES': list(mc.ACTION_NAMES), 'ACT_LAST': mc.ACT_LAST, 'VEL_CURVES': list(mc.VEL_CURVES), 'SCALE_NAMES': list(mc.SCALE_NAMES), 'ARP_TYPES': list(mc.ARP_TYPES), 'ARP_RATES': list(mc.ARP_RATES), 'CHORD_NAMES': list(mc.CHORD_NAMES), 'PRESS_MODES': list(mc.PRESS_MODES), 'ENC_MODES': list(mc.ENC_MODES), 'BTN_MODES': list(mc.BTN_MODES),
        'BUTTON_NAMES': mc.BUTTON_NAMES, 'PAD_LABEL': mc.PAD_LABEL, 'COLOUR_NAMES': mc.COLOUR_NAMES,
        'NI_BUTTON_CC': {str(k): v for k, v in mc.NI_BUTTON_CC.items()},
        'FIELDS': {k: list(v) for k, v in mc.FIELDS.items()},
        'RANGES': {k: [lo, hi, ff] for k, (lo, hi, ff) in mc.RANGES.items()},
        'LED_FLAGS': {'BTN_IDLE': mc.LF_BTN_IDLE, 'BTN_PRESS': mc.LF_BTN_PRESS, 'PAD_IDLE': mc.LF_PAD_IDLE, 'PAD_HIT': mc.LF_PAD_HIT, 'STRIP': mc.LF_STRIP},
        'BTN_PLAY': mc.BTN_PLAY, 'BTN_REC': mc.BTN_REC, 'BTN_STOP': mc.BTN_STOP,
        'REC_MAGIC': mc.REC_MAGIC, 'REC_VERSION': mc.REC_VERSION, 'REC_SIZE': mc.REC_SIZE,
        'PRESETS_HEX': {k: v.hex() for k, v in presets.items()},
        'BUILTIN_PRESETS': [{'id': p['id'], 'name': p['name'], 'description': p['description'], 'cfg_hex': p['cfg'].hex()} for p in mc.builtin_presets()],
        'PRESET_FILE_FORMAT': mc.PRESET_FILE_FORMAT,
    }
    out = ['// GENERATED by tools/ui/gen_data.py from tools/midi_patch/mmk3_config.py: do not edit.']
    for k, v in data.items(): out.append(f'export const {k} = {json.dumps(v, indent=None)};')
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    path = os.path.join(HERE, 'mmk3_data.js'); text = render()
    if '--check' in sys.argv:
        ok = os.path.exists(path) and open(path).read() == text
        print('mmk3_data.js is up to date' if ok else 'mmk3_data.js is out of date: run tools/ui/gen_data.py'); sys.exit(0 if ok else 1)
    open(path, 'w').write(text); print('written', path, len(text), 'bytes')
